package deskwork

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"mime/multipart"
	"net/textproto"
	"path"
	"strings"
)

const MaxFrontendBytes int64 = 32 << 20
const MaxFrontendFiles = 2048

// FrontendManifest binds both bytes and MIME types. Docket hashes its complete
// path-to-MIME map, not a directory name or just the concatenated file bytes.
// This is an immutable prepared artifact, not permission to upload it.
type FrontendAsset struct {
	File        File   `json:"file"`
	ContentType string `json:"content_type"`
}
type FrontendManifest struct {
	Version int             `json:"version"`
	Files   []FrontendAsset `json:"files"`
	Digest  string          `json:"digest"`
}

func frontendDigest(files []FrontendAsset) string {
	b, _ := json.Marshal(files)
	hash := sha256.Sum256(b)
	return hex.EncodeToString(hash[:])
}

// Keep MIME selection deterministic across hosts; system mime databases must
// not change a reviewed glob. Unknown extensions are explicit binary assets.
func frontendContentType(name string) string {
	switch path.Ext(name) {
	case ".html", ".htm":
		return "text/html"
	case ".css":
		return "text/css"
	case ".js", ".mjs":
		return "application/javascript"
	case ".json", ".map":
		return "application/json"
	case ".svg":
		return "image/svg+xml"
	case ".png":
		return "image/png"
	case ".jpg", ".jpeg":
		return "image/jpeg"
	case ".gif":
		return "image/gif"
	case ".webp":
		return "image/webp"
	case ".avif":
		return "image/avif"
	case ".ico":
		return "image/x-icon"
	case ".woff":
		return "font/woff"
	case ".woff2":
		return "font/woff2"
	case ".ttf":
		return "font/ttf"
	case ".otf":
		return "font/otf"
	case ".wasm":
		return "application/wasm"
	case ".txt":
		return "text/plain"
	case ".xml":
		return "application/xml"
	case ".webmanifest":
		return "application/manifest+json"
	case ".mp4":
		return "video/mp4"
	case ".webm":
		return "video/webm"
	case ".mp3":
		return "audio/mpeg"
	case ".ogg":
		return "audio/ogg"
	case ".wav":
		return "audio/wav"
	default:
		return "application/octet-stream"
	}
}

func NewFrontendManifest(source Manifest) (FrontendManifest, error) {
	if err := source.Validate(); err != nil {
		return FrontendManifest{}, err
	}
	files := make([]FrontendAsset, 0, len(source.Files))
	for _, f := range source.Files {
		files = append(files, FrontendAsset{File: f, ContentType: frontendContentType(f.Path)})
	}
	out := FrontendManifest{Version: 1, Files: files, Digest: frontendDigest(files)}
	return out, out.Validate()
}

func (m FrontendManifest) Validate() error {
	if m.Version != 1 || m.Files == nil || len(m.Files) == 0 || len(m.Files) > MaxFrontendFiles || m.Digest != frontendDigest(m.Files) {
		return errors.New("invalid frontend manifest")
	}
	var total int64
	index := false
	files := make([]File, 0, len(m.Files))
	for i, f := range m.Files {
		// desk.js is generated by Docket, not served from the submitted map.
		// DS_Store is silently discarded by its native upload parser.
		base := path.Base(f.File.Path)
		if f.File.Path == "desk.js" || base == "DS_Store" || strings.HasPrefix(base, ".") || f.ContentType != frontendContentType(f.File.Path) || i > 0 && m.Files[i-1].File.Path >= f.File.Path {
			return errors.New("unsupported or changed frontend path/type")
		}
		if f.File.Path == "index.html" {
			index = true
		}
		total += f.File.Bytes
		files = append(files, f.File)
	}
	if !index || total > MaxFrontendBytes {
		return errors.New("frontend requires index.html and at most 32 MiB")
	}
	_, err := NewManifest(files)
	return err
}

// FrontendMultipart matches Docket's existing directory upload: a fixed first
// directory component is stripped by its parser. Every supplied file is checked
// against the complete frozen artifact before any HTTP request is constructed.
func FrontendMultipart(desk string, m FrontendManifest, files []SourceFile) ([]byte, string, error) {
	if !deskName.MatchString(desk) {
		return nil, "", errors.New("invalid frontend upload")
	}
	if err := validateFrontendFiles(m, files); err != nil {
		return nil, "", err
	}
	var out bytes.Buffer
	w := multipart.NewWriter(&out)
	if err := w.SetBoundary("omabit-" + m.Digest[:48]); err != nil {
		return nil, "", err
	}
	if err := w.WriteField("desk", desk); err != nil {
		return nil, "", err
	}
	for i, f := range files {
		expected := m.Files[i]
		part, err := w.CreatePart(textproto.MIMEHeader{"Content-Disposition": {`form-data; name="glob"; filename="bundle/` + f.Path + `"`}, "Content-Type": {expected.ContentType}})
		if err != nil {
			return nil, "", err
		}
		if _, err = part.Write(f.Bytes); err != nil {
			return nil, "", err
		}
	}
	if err := w.Close(); err != nil {
		return nil, "", err
	}
	return out.Bytes(), w.FormDataContentType(), nil
}

func validateFrontendFiles(m FrontendManifest, files []SourceFile) error {
	if m.Validate() != nil || len(files) != len(m.Files) {
		return errors.New("invalid frontend artifact")
	}
	for i, f := range files {
		expected := m.Files[i].File
		hash := sha256.Sum256(f.Bytes)
		if f.Path != expected.Path || int64(len(f.Bytes)) != expected.Bytes || hex.EncodeToString(hash[:]) != expected.SHA256 {
			return errors.New("frontend differs from frozen artifact")
		}
		// Docket's multipart parser returns an atom, and handle-upload then uses
		// as-octs to infer its length. A final zero byte would be silently lost.
		// Refuse before sending instead of modifying the developer's artifact.
		if len(f.Bytes) > 0 && f.Bytes[len(f.Bytes)-1] == 0 {
			return errors.New("native Docket upload cannot preserve a file ending in a zero byte")
		}
	}
	return nil
}
