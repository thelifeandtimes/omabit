#!/usr/bin/env python3
"""Generate/check the public CLI reference from built tools in a networkless sandbox.

Requires bwrap. Only copied binaries, a private HOME and read-only /usr are visible;
help is never evaluated against a real registry, host runtime or desktop session.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

TOOLS = ('omabit', 'urbit-collector', 'urbit-runner')

def collect(binary_dir):
    with tempfile.TemporaryDirectory(prefix='omabit-cli-reference-') as tmp:
        work = Path(tmp)
        for name in TOOLS:
            shutil.copyfile(binary_dir / name, work / name)
            (work / name).chmod(0o700)
        for name in ('home', 'runtime'):
            (work / name).mkdir(mode=0o700)
        prefix = ['bwrap', '--unshare-all', '--die-with-parent', '--clearenv',
                  '--ro-bind', '/usr', '/usr', '--symlink', 'usr/bin', '/bin',
                  '--symlink', 'usr/lib', '/lib', '--symlink', 'usr/lib', '/lib64',
                  '--proc', '/proc', '--dev', '/dev', '--tmpfs', '/tmp',
                  '--bind', str(work), '/lab', '--chdir', '/lab',
                  '--setenv', 'HOME', '/lab/home', '--setenv', 'XDG_RUNTIME_DIR', '/lab/runtime',
                  '--setenv', 'PATH', '/usr/bin:/bin', '--']
        records = []
        def call(binary, args):
            result = subprocess.run(prefix + ['/lab/' + binary, *args], capture_output=True,
                                    text=True, timeout=10)
            text = "\n".join(line.expandtabs(8).rstrip() for line in (result.stdout + result.stderr).strip().splitlines())
            if result.returncode or not text:
                raise RuntimeError(f'{binary} {args}: help failed ({result.returncode}): {text}')
            records.append({'binary': binary, 'args': args, 'text': text})
            return text
        for binary in TOOLS:
            text = call(binary, ['--help'])
            if binary == 'omabit':
                commands = re.findall(r'(?:Commands: |, )([a-z][a-z-]+)', text)
            else:
                commands = re.findall(r'^  ([a-z][a-z-]+)(?:\s|$)', text, re.M)
            commands = sorted(set(commands) - {'urbit-runner'})
            if not commands:
                raise RuntimeError('command discovery returned no public commands: ' + binary)
            for command in commands:
                if command == 'help':
                    call(binary, ['--format', 'text', 'help'])
                    for topic in ('runners', 'ships', 'projects', 'imports', 'connections', 'hosting'):
                        call(binary, ['--format', 'text', 'help', topic])
                else:
                    call(binary, [command, '--help'])
        # Even bad help implementations may not write a registry as a side effect.
        if list((work / 'home').rglob('*')):
            raise RuntimeError('help created state in its private HOME')
        return records

def documents(records):
    result = {}
    for binary in TOOLS:
        chunks = [f'# {binary} command reference\n',
                  'Generated from the built command help. Do not edit this file by hand.\n',
                  'Global options precede the command. Command options follow its positional arguments.\n']
        for record in records:
            if record['binary'] != binary:
                continue
            title = 'Overview' if record['args'] == ['--help'] else ' '.join(record['args']).replace('--format text ', '').replace(' --help', '')
            chunks += [f'## {title}\n', '```text\n' + record['text'] + '\n```\n']
        result[binary + '.md'] = '\n'.join(chunks)
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bin-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    records = collect(args.bin_dir.resolve())
    for name, text in documents(records).items():
        path = args.output / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit('CLI reference differs: ' + str(path))
        else:
            args.output.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(json.dumps({'passed': True, 'help_entries': len(records), 'networkless': True,
                      'state_untouched': True, 'check': args.check}))

if __name__ == '__main__':
    main()
